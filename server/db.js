import { DatabaseSync } from 'node:sqlite';
import { mkdirSync } from 'node:fs';
import path from 'node:path';

/**
 * The library, server side.
 *
 * SQLite through node's built-in driver, so the service has no npm
 * dependencies at all and deploying it is copying files. The data directory
 * lives outside the deploy directory on purpose: the deploy rsyncs with
 * --delete, and a database inside it would be erased on the next push.
 */

export const DATA_DIR = process.env.BOOKSHELF_DATA || '/var/lib/bookshelf';
export const COVER_DIR = path.join(DATA_DIR, 'covers');

let db;

export function initDb() {
  mkdirSync(COVER_DIR, { recursive: true });
  db = new DatabaseSync(path.join(DATA_DIR, 'bookshelf.db'));
  // WAL so a long read cannot block a write, and foreign keys so deleting an
  // account actually takes its books with it.
  db.exec('PRAGMA journal_mode = WAL');
  db.exec('PRAGMA foreign_keys = ON');
  db.exec(`
    CREATE TABLE IF NOT EXISTS users (
      id            INTEGER PRIMARY KEY AUTOINCREMENT,
      username      TEXT NOT NULL UNIQUE COLLATE NOCASE,
      password_hash TEXT NOT NULL,
      created_at    TEXT NOT NULL
    );

    CREATE TABLE IF NOT EXISTS sessions (
      token_hash TEXT PRIMARY KEY,
      user_id    INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
      created_at INTEGER NOT NULL,
      expires_at INTEGER NOT NULL,
      last_seen  INTEGER NOT NULL,
      user_agent TEXT
    );
    CREATE INDEX IF NOT EXISTS idx_sessions_user ON sessions(user_id);

    -- Ids are generated by the client, which lets a library built offline be
    -- uploaded without renumbering anything.
    CREATE TABLE IF NOT EXISTS books (
      user_id        INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
      id             TEXT NOT NULL,
      title          TEXT NOT NULL DEFAULT '',
      subtitle       TEXT,
      authors        TEXT NOT NULL DEFAULT '[]',
      publisher      TEXT,
      published_date TEXT,
      page_count     INTEGER,
      isbn13         TEXT,
      isbn10         TEXT,
      language       TEXT,
      description    TEXT,
      subjects       TEXT NOT NULL DEFAULT '[]',
      source         TEXT NOT NULL DEFAULT 'manual',
      cover_aspect   REAL,
      /* Changes whenever the artwork does, so the client can cache a cover
         forever and still pick up a replacement. */
      cover_etag     TEXT,
      rating         INTEGER NOT NULL DEFAULT 0,
      read_status    TEXT NOT NULL DEFAULT 'unread',
      date_added     INTEGER NOT NULL,
      sort_index     INTEGER NOT NULL DEFAULT 0,
      list_ids       TEXT NOT NULL DEFAULT '[]',
      updated_at     INTEGER NOT NULL,
      PRIMARY KEY (user_id, id)
    );

    CREATE TABLE IF NOT EXISTS lists (
      user_id      INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
      id           TEXT NOT NULL,
      name         TEXT NOT NULL,
      sort_index   INTEGER NOT NULL DEFAULT 0,
      date_created INTEGER NOT NULL,
      updated_at   INTEGER NOT NULL,
      PRIMARY KEY (user_id, id)
    );
  `);
  return db;
}

export const database = () => db;

const parse = (s, fallback) => {
  try {
    return JSON.parse(s);
  } catch {
    return fallback;
  }
};

// MARK: - Users

export function createUser(username, passwordHash) {
  const stmt = db.prepare(
    'INSERT INTO users (username, password_hash, created_at) VALUES (?, ?, ?)'
  );
  const info = stmt.run(username, passwordHash, new Date().toISOString());
  return Number(info.lastInsertRowid);
}

export const findUser = (username) =>
  db.prepare('SELECT * FROM users WHERE username = ?').get(username);

export const userById = (id) =>
  db.prepare('SELECT id, username, created_at FROM users WHERE id = ?').get(id);

export const countUsers = () => db.prepare('SELECT COUNT(*) AS n FROM users').get().n;

// MARK: - Sessions

export function createSession(tokenHash, userId, expiresAt, userAgent) {
  const now = Date.now();
  db.prepare(
    `INSERT INTO sessions (token_hash, user_id, created_at, expires_at, last_seen, user_agent)
     VALUES (?, ?, ?, ?, ?, ?)`
  ).run(tokenHash, userId, now, expiresAt, now, userAgent ?? null);
}

export function sessionByHash(tokenHash) {
  return db.prepare('SELECT * FROM sessions WHERE token_hash = ?').get(tokenHash);
}

export function touchSession(tokenHash, expiresAt) {
  db.prepare('UPDATE sessions SET last_seen = ?, expires_at = ? WHERE token_hash = ?').run(
    Date.now(),
    expiresAt,
    tokenHash
  );
}

export const deleteSession = (tokenHash) =>
  db.prepare('DELETE FROM sessions WHERE token_hash = ?').run(tokenHash);

export const purgeExpiredSessions = () =>
  db.prepare('DELETE FROM sessions WHERE expires_at < ?').run(Date.now());

// MARK: - Books

const BOOK_COLUMNS = [
  'id',
  'title',
  'subtitle',
  'authors',
  'publisher',
  'published_date',
  'page_count',
  'isbn13',
  'isbn10',
  'language',
  'description',
  'subjects',
  'source',
  'cover_aspect',
  'cover_etag',
  'rating',
  'read_status',
  'date_added',
  'sort_index',
  'list_ids',
  'updated_at'
];

function rowToBook(row) {
  return {
    id: row.id,
    title: row.title,
    subtitle: row.subtitle,
    authors: parse(row.authors, []),
    publisher: row.publisher,
    publishedDate: row.published_date,
    pageCount: row.page_count,
    isbn13: row.isbn13,
    isbn10: row.isbn10,
    language: row.language,
    description: row.description,
    subjects: parse(row.subjects, []),
    source: row.source,
    coverAspect: row.cover_aspect,
    coverEtag: row.cover_etag,
    rating: row.rating,
    readStatus: row.read_status,
    dateAdded: row.date_added,
    sortIndex: row.sort_index,
    listIds: parse(row.list_ids, []),
    updatedAt: row.updated_at
  };
}

export function listBooks(userId) {
  return db
    .prepare(`SELECT ${BOOK_COLUMNS.join(', ')} FROM books WHERE user_id = ? ORDER BY sort_index`)
    .all(userId)
    .map(rowToBook);
}

export function getBook(userId, id) {
  const row = db
    .prepare(`SELECT ${BOOK_COLUMNS.join(', ')} FROM books WHERE user_id = ? AND id = ?`)
    .get(userId, id);
  return row ? rowToBook(row) : null;
}

export function upsertBook(userId, book) {
  db.prepare(
    `INSERT INTO books (
       user_id, id, title, subtitle, authors, publisher, published_date, page_count,
       isbn13, isbn10, language, description, subjects, source, cover_aspect,
       rating, read_status, date_added, sort_index, list_ids, updated_at
     ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
     ON CONFLICT(user_id, id) DO UPDATE SET
       title = excluded.title,
       subtitle = excluded.subtitle,
       authors = excluded.authors,
       publisher = excluded.publisher,
       published_date = excluded.published_date,
       page_count = excluded.page_count,
       isbn13 = excluded.isbn13,
       isbn10 = excluded.isbn10,
       language = excluded.language,
       description = excluded.description,
       subjects = excluded.subjects,
       source = excluded.source,
       cover_aspect = excluded.cover_aspect,
       rating = excluded.rating,
       read_status = excluded.read_status,
       date_added = excluded.date_added,
       sort_index = excluded.sort_index,
       list_ids = excluded.list_ids,
       updated_at = excluded.updated_at`
  ).run(
    userId,
    book.id,
    book.title ?? '',
    book.subtitle ?? null,
    JSON.stringify(book.authors ?? []),
    book.publisher ?? null,
    book.publishedDate ?? null,
    book.pageCount ?? null,
    book.isbn13 ?? null,
    book.isbn10 ?? null,
    book.language ?? null,
    book.description ?? null,
    JSON.stringify(book.subjects ?? []),
    book.source ?? 'manual',
    book.coverAspect ?? null,
    book.rating ?? 0,
    book.readStatus ?? 'unread',
    book.dateAdded ?? Date.now(),
    book.sortIndex ?? 0,
    JSON.stringify(book.listIds ?? []),
    Date.now()
  );
  return getBook(userId, book.id);
}

export function setCoverEtag(userId, id, etag, aspect) {
  db.prepare(
    'UPDATE books SET cover_etag = ?, cover_aspect = COALESCE(?, cover_aspect), updated_at = ? WHERE user_id = ? AND id = ?'
  ).run(etag, aspect ?? null, Date.now(), userId, id);
}

export const deleteBook = (userId, id) =>
  db.prepare('DELETE FROM books WHERE user_id = ? AND id = ?').run(userId, id);

// MARK: - Collections

const rowToList = (row) => ({
  id: row.id,
  name: row.name,
  sortIndex: row.sort_index,
  dateCreated: row.date_created
});

export const listLists = (userId) =>
  db
    .prepare('SELECT * FROM lists WHERE user_id = ? ORDER BY sort_index')
    .all(userId)
    .map(rowToList);

export function upsertList(userId, list) {
  db.prepare(
    `INSERT INTO lists (user_id, id, name, sort_index, date_created, updated_at)
     VALUES (?, ?, ?, ?, ?, ?)
     ON CONFLICT(user_id, id) DO UPDATE SET
       name = excluded.name,
       sort_index = excluded.sort_index,
       updated_at = excluded.updated_at`
  ).run(
    userId,
    list.id,
    list.name ?? '',
    list.sortIndex ?? 0,
    list.dateCreated ?? Date.now(),
    Date.now()
  );
  return list;
}

export const deleteList = (userId, id) =>
  db.prepare('DELETE FROM lists WHERE user_id = ? AND id = ?').run(userId, id);
